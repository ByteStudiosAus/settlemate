// ── plans / subscriptions (native recurring payments) ────────────────────────
//
// Verified live against the sandbox (2026-07): a Plan is a reusable schedule
// template; a Subscription binds it to one payer and actually generates the
// individual payment records. `fixedPayments` lets each occurrence carry its
// OWN amountInCents (so create_payment_plan's remainder-on-final-instalment
// split survives exactly — Pinch's `recurringPayment` field only supports a
// single repeating amount, which can't represent that). Cancelling the
// SUBSCRIPTION (DELETE /subscriptions/{id}) removes every not-yet-taken
// payment it generated in one call — confirmed live: the payer's payment list
// was empty immediately after.

export interface PinchFixedPayment {
  amountInCents: number;
  description: string;
  /** Offset from the subscription's startDate, in `scheduledDateInterval` units. */
  scheduledDateOffset: number;
  scheduledDateInterval: "days" | "months" | "years";
  cancelPlanOnFailure?: boolean;
}

export interface PinchPlan {
  id: string;
  name: string;
  fixedPayments?: PinchFixedPayment[];
  subscriberCount?: number;
  requiresTotalAmount?: boolean;
  [k: string]: unknown;
}

/** POST /plans — create a plan (a schedule template with no payer attached yet). */
export function createPlan(
  env: Env,
  input: { name: string; fixedPayments: PinchFixedPayment[] },
): Promise<PinchPlan | StructuredError> {
  return pinchRequest<PinchPlan>(env, "POST", "/plans", input);
}

/**
 * DELETE /plans/{id}. Pinch only allows deleting a plan with zero subscribers,
 * so this is only ever called to clean up a plan whose subscription creation
 * failed (never one already bound to a payer).
 */
export async function deletePlan(
  env: Env,
  planId: string,
): Promise<{ ok: true; id: string } | StructuredError> {
  const res = await pinchRequest<unknown>(env, "DELETE", `/plans/${encodeURIComponent(planId)}`);
  if (isStructuredError(res)) return res;
  return { ok: true, id: planId };
}

