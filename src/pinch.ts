// ── OAuth token cache ────────────────────────────────────────────────────────

interface CachedToken {
  access_token: string;
  /** epoch milliseconds at which the token expires */
  expires_at: number;
}

const TOKEN_KV_KEY = "pinch:token";
/** Refresh this many ms before the real expiry so in-flight calls never 401. */
const TOKEN_REFRESH_SKEW_MS = 60_000;

/**
 * The OAuth client_id.
 *
 * NOTE: client_id is the APPLICATION ID (app_...), NOT the publishable key
 * (pk_...) — Pinch's own docs wording is misleading here; verified against a
 * live sandbox 200. There is no dedicated PINCH_APPLICATION_ID binding, so we
 * store the Application ID in the PINCH_PUBLISHABLE_KEY secret. If auth 401s,
 * put the real app_... value there.
 */
function getClientId(env: Env): string {
  return env.PINCH_PUBLISHABLE_KEY;
}

/**
 * Return a valid bearer token, minting + caching a fresh one when the cached
 * token is missing or within the refresh skew of expiry.
 */
export async function getToken(env: Env): Promise<string | StructuredError> {
  try {
    const cached = (await env.TOKENS.get(TOKEN_KV_KEY, "json")) as CachedToken | null;
    if (cached && cached.expires_at - Date.now() > TOKEN_REFRESH_SKEW_MS) {
      return cached.access_token;
    }

    const body = new URLSearchParams({
      grant_type: "client_credentials",
      client_id: getClientId(env),
      client_secret: env.PINCH_SECRET_KEY,
    });

    const res = await fetch(env.PINCH_AUTH_URL, {
      method: "POST",
      headers: { "content-type": "application/x-www-form-urlencoded" },
      body,
    });

    const text = await res.text();
    let parsed: unknown;
    try {
      parsed = text ? JSON.parse(text) : {};
    } catch {
      parsed = { raw: text };
    }

    if (!res.ok) {
      return structuredError("oauth_failed", "Pinch OAuth token request failed", {
        status: res.status,
        body: parsed,
      });
    }

    const token = parsed as {
      access_token?: string;
      expires_in?: number;
      token_type?: string;
    };
    if (!token.access_token) {
      return structuredError("oauth_failed", "OAuth response missing access_token", {
        body: parsed,
      });
    }

    const expiresInSec = typeof token.expires_in === "number" ? token.expires_in : 3600;
    const record: CachedToken = {
      access_token: token.access_token,
      expires_at: Date.now() + expiresInSec * 1000,
    };
    // TTL the KV entry to the token lifetime so a stale token never lingers.
    await env.TOKENS.put(TOKEN_KV_KEY, JSON.stringify(record), {
      expirationTtl: Math.max(60, expiresInSec),
    });

    return record.access_token;
  } catch (err) {
    return structuredError("network_error", "Failed to reach Pinch OAuth endpoint", {
      cause: String(err),
    });
  }
}

// ── error normalisation ──────────────────────────────────────────────────────

/**
 * Pinch returns errors in two different shapes depending on the endpoint:
 *   1. { errors: [{ message, field }] }
 *   2. bare array of { propertyName, errorMessage, ... }
 * Normalise BOTH into our StructuredError. The raw body is kept in `details`.
 */
function normalisePinchError(body: unknown, status: number): StructuredError {
  // Shape 2: bare array of { propertyName, errorMessage }
  if (Array.isArray(body)) {
    const messages = body
      .map((e) => {
        const item = e as { propertyName?: string; errorMessage?: string };
        if (item.errorMessage) {
          return item.propertyName
            ? `${item.propertyName}: ${item.errorMessage}`
            : item.errorMessage;
        }
        return null;
      })
      .filter((m): m is string => m !== null);
    return structuredError(
      "pinch_error",
      messages.length ? messages.join("; ") : `Pinch request failed (HTTP ${status})`,
      { status, body },
    );
  }

  // Shape 1: { errors: [{ message, field }] }
  if (body && typeof body === "object" && "errors" in body) {
    const errs = (body as { errors?: unknown }).errors;
    if (Array.isArray(errs)) {
      const messages = errs
        .map((e) => {
          const item = e as { message?: string; field?: string };
          if (item.message) {
            return item.field ? `${item.field}: ${item.message}` : item.message;
          }
          return null;
        })
        .filter((m): m is string => m !== null);
      return structuredError(
        "pinch_error",
        messages.length ? messages.join("; ") : `Pinch request failed (HTTP ${status})`,
        { status, body },
      );
    }
  }

  // Fallback: unknown shape.
  return structuredError("pinch_error", `Pinch request failed (HTTP ${status})`, {
    status,
    body,
  });
}

// ── low-level authenticated request ──────────────────────────────────────────

async function pinchRequest<T>(
  env: Env,
  method: string,
  path: string,
  body?: unknown,
): Promise<T | StructuredError> {
  const token = await getToken(env);
  if (typeof token !== "string") return token; // propagate StructuredError

  try {
    const init: RequestInit = {
      method,
      headers: {
        Authorization: `Bearer ${token}`,
        "pinch-version": env.PINCH_VERSION,
        "content-type": "application/json",
      },
    };
    if (body !== undefined) init.body = JSON.stringify(body);

    const res = await fetch(`${env.PINCH_API_BASE}${path}`, init);
    const text = await res.text();
    let parsed: unknown;
    try {
      parsed = text ? JSON.parse(text) : {};
    } catch {
      parsed = { raw: text };
    }

    if (!res.ok) return normalisePinchError(parsed, res.status);
    return parsed as T;
  } catch (err) {
    return structuredError("network_error", `Failed to reach Pinch API (${path})`, {
      cause: String(err),
    });
  }
}

