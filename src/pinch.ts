/**
 * Resolve which bank-account source to charge for a payer's realtime payment.
 * Pinch's docs say realtime `sourceId` defaults to the payer's default when
 * empty, but the sandbox rejects a source-less realtime charge ("Bank Account
 * required when no token is specified"), so we look one up explicitly:
 * GET the payer and pick the first bank-account source (preferring one that
 * `supportsRealtime`). Returns the src_ id, or a StructuredError if none exists.
 */
export async function resolveBankSourceId(
  env: Env,
  payerId: string,
): Promise<string | StructuredError> {
  const payer = await getPayer(env, payerId);
  if (typeof payer !== "object" || payer === null || "error" in payer) {
    return payer as StructuredError;
  }
  const sources = Array.isArray(payer.sources) ? payer.sources : [];
  const bankSources = sources.filter((s) => s.sourceType === "bank-account");
  // Prefer a realtime-capable, authorised source; fall back to the first bank account.
  const preferred =
    bankSources.find((s) => s.supportsRealtime && s.isAuthorised !== false) ??
    bankSources.find((s) => s.supportsRealtime) ??
    bankSources[0];
  if (!preferred) {
    return structuredError(
      "no_payment_source",
      `Payer "${payerId}" has no bank-account source to charge. Add one with add_bank_account first.`,
      { payerId },
    );
  }
  return preferred.id;
}

